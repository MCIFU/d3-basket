const norm = (s: string) =>
  s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z]/g, '')
const BY = new Map<string, [string, string]>()
for (const [cc, name, ...alias] of T) for (const a of [cc, name, ...alias]) BY.set(norm(a), [cc, name])

/** País normalizado a partir de la nacionalidad tal como llega de la fuente (primera si son varias). */
export function country(raw: string | null | undefined): { cc: string; name: string } | null {
  if (!raw) return null
  const first = raw.split(/[/-]/)[0].trim()
  const hit = BY.get(norm(first)) ?? BY.get(norm(raw))
  return hit ? { cc: hit[0], name: hit[1] } : null
}
/** Emoji de bandera a partir de un código ISO de dos letras. */
export const flagOf = (cc: string | null | undefined) => (cc && /^[A-Z]{2}$/.test(cc) ? String.fromCodePoint(...[...cc].map((c) => 0x1f1a5 + c.charCodeAt(0))) : '')
